package eu.mikart.tava.oracle;

import eu.mikart.tava.jdbc.JdbcAdapter;
import eu.mikart.tava.jdbc.JdbcProfile;
import eu.mikart.tava.jdbc.StandardJdbcProfile;
import eu.mikart.tava.schema.FieldDefinition;
import eu.mikart.tava.schema.GeneratedValue;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import javax.sql.DataSource;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;
import org.jetbrains.annotations.Range;

/** Factory methods for Oracle database adapters. */
public final class Oracle {
    private Oracle() {}

    /**
     * Creates an Oracle adapter using application-managed JDBC connections.
     *
     * @param dataSource connection pool or other JDBC data source
     * @return adapter backed by the data source
     * @since 1.3.0
     */
    public static @NotNull JdbcAdapter connect(final @NotNull DataSource dataSource) {
        Objects.requireNonNull(dataSource, "dataSource");
        return new JdbcAdapter(new Profile(), dataSource::getConnection);
    }

    /**
     * Creates an Oracle adapter using a JDBC connection URL.
     *
     * @param url JDBC connection URL
     * @param user database user
     * @param password database password
     * @return adapter that owns the opened connections
     */
    public static @NotNull JdbcAdapter connect(
            final @NotNull String url, final @NotNull String user, final @NotNull String password) {
        return JdbcAdapter.driverManager(new Profile(), url, user, password);
    }

    private static final class Profile extends StandardJdbcProfile {
        private Profile() {
            super("oracle", '"', false);
        }

        @Override
        public @NotNull String type(final @NotNull FieldDefinition field) {
            return switch (field.type().logicalType()) {
                case UUID -> "VARCHAR2(36)";
                case JSON, TEXT -> "CLOB";
                case STRING ->
                    "VARCHAR2("
                            + (field.type().length() == null
                                    ? 255
                                    : field.type().length()) + ")";
                case INT32 -> "NUMBER(10)";
                case INT64 -> "NUMBER(19)";
                case FLOAT64 -> "BINARY_DOUBLE";
                case BOOLEAN -> "NUMBER(1)";
                case BINARY -> "BLOB";
                case INSTANT -> "TIMESTAMP WITH TIME ZONE";
                default -> super.type(field);
            };
        }

        @Override
        public @NotNull String identityClause(final @NotNull FieldDefinition field) {
            return field.generated() == GeneratedValue.IDENTITY ? "GENERATED BY DEFAULT AS IDENTITY" : "";
        }

        @Override
        public @NotNull List<JdbcProfile.IndexColumn> indexColumns(
                final @NotNull Connection connection,
                final @Nullable String catalog,
                final @Nullable String schema,
                final @NotNull String table)
                throws SQLException {
            String owner = schema == null ? connection.getSchema() : schema;
            String sql = "SELECT i.INDEX_NAME, c.COLUMN_NAME, c.COLUMN_POSITION, i.UNIQUENESS "
                    + "FROM ALL_INDEXES i JOIN ALL_IND_COLUMNS c "
                    + "ON c.INDEX_OWNER = i.OWNER AND c.INDEX_NAME = i.INDEX_NAME "
                    + "AND c.TABLE_OWNER = i.TABLE_OWNER AND c.TABLE_NAME = i.TABLE_NAME "
                    + "WHERE i.TABLE_OWNER = ? AND i.TABLE_NAME = ? "
                    + "ORDER BY i.INDEX_NAME, c.COLUMN_POSITION";
            List<JdbcProfile.IndexColumn> columns = new ArrayList<>();
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                statement.setString(1, owner);
                statement.setString(2, table);
                try (ResultSet result = statement.executeQuery()) {
                    while (result.next()) {
                        columns.add(new JdbcProfile.IndexColumn(
                                result.getString("INDEX_NAME"), result.getString("COLUMN_NAME"),
                                result.getInt("COLUMN_POSITION"), "UNIQUE".equals(result.getString("UNIQUENESS"))));
                    }
                }
            }
            return List.copyOf(columns);
        }

        @Override
        public @NotNull String pagination(
                final @Range(from = 1, to = Integer.MAX_VALUE) int limit,
                final @Range(from = 0, to = Integer.MAX_VALUE) int offset) {
            return " OFFSET " + offset + " ROWS FETCH NEXT " + limit + " ROWS ONLY";
        }

        @Override
        public @NotNull String defaultPaginationOrder() {
            return " ORDER BY 1";
        }
    }
}

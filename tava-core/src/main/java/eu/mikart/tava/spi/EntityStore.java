package eu.mikart.tava.spi;

import eu.mikart.tava.TavaException.Capability;
import eu.mikart.tava.TavaException.Conflict;
import eu.mikart.tava.data.ConflictDetail;
import eu.mikart.tava.data.EntityRecord;
import eu.mikart.tava.data.MutationResult;
import eu.mikart.tava.data.Page;
import eu.mikart.tava.query.Mutation;
import eu.mikart.tava.query.Pages;
import eu.mikart.tava.query.Predicate;
import eu.mikart.tava.query.Query;
import eu.mikart.tava.query.QueryDiagnostics;
import java.util.List;
import org.jetbrains.annotations.NotNull;

/** Executes entity reads and writes for an adapter. */
public interface EntityStore {
    /**
     * Inserts one record.
     *
     * @param entity entity name
     * @param record record to insert
     * @return stored record, including values generated by the adapter
     * @throws Conflict if a unique constraint rejects the record
     */
    @NotNull
    EntityRecord insert(@NotNull String entity, @NotNull EntityRecord record);

    /**
     * Inserts records in input order.
     *
     * <p>The default implementation inserts one record at a time and may leave earlier records stored if a later insert
     * fails. Adapters declaring {@code ATOMIC_BULK_WRITE} roll back the entire batch on failure; their
     * {@code BULK_WRITE.batchSize} capability, when present, limits the atomic batch size.
     *
     * @param entity entity name
     * @param records records to insert
     * @return stored records in input order
     * @throws Conflict if a unique constraint rejects a record
     */
    default @NotNull List<EntityRecord> insert(
            final @NotNull String entity, final @NotNull List<EntityRecord> records) {
        return records.stream().map(record -> insert(entity, record)).toList();
    }

    /**
     * Finds a page of records matching a query.
     *
     * @param entity entity name
     * @param query filters, projection, ordering, and page options
     * @return page of records and an optional continuation cursor
     */
    @NotNull
    Page<EntityRecord> find(@NotNull String entity, @NotNull Query query);

    /**
     * Counts matching records. Adapters should override this fallback with server-side counting.
     *
     * @param entity entity name
     * @param predicate matching condition
     * @return matching record count
     * @since 1.3.0
     */
    default long count(String entity, Predicate predicate) {
        try (var stream = Pages.stream(Query.builder().where(predicate).build(), query -> find(entity, query))) {
            return stream.count();
        }
    }

    /**
     * Checks for a match, following empty filtered pages when necessary.
     *
     * @param entity entity name
     * @param predicate matching condition
     * @return whether a match exists
     * @since 1.3.0
     */
    default boolean exists(String entity, Predicate predicate) {
        try (var stream =
                Pages.stream(Query.builder().where(predicate).limit(1).build(), query -> find(entity, query))) {
            return stream.findFirst().isPresent();
        }
    }

    /**
     * Describes portable query planning without executing the query.
     *
     * @param entity entity name
     * @param query query to inspect
     * @return adapter access-path information
     * @since 1.3.0
     */
    default QueryDiagnostics explain(String entity, Query query) {
        return new QueryDiagnostics(
                "unspecified", query.sorting(), false, "Adapter does not expose access-path diagnostics");
    }

    /**
     * Applies a mutation to records matching a predicate.
     *
     * @param entity entity name
     * @param predicate condition selecting records
     * @param mutation changes to apply
     * @return number of records reported as updated
     */
    long update(@NotNull String entity, @NotNull Predicate predicate, @NotNull Mutation mutation);

    /**
     * Deletes records matching a predicate.
     *
     * @param entity entity name
     * @param predicate condition selecting records
     * @return number of records reported as deleted
     */
    long delete(@NotNull String entity, @NotNull Predicate predicate);

    /**
     * Inserts one record and returns its outcome.
     *
     * <p>The default implementation converts unique-key conflicts into a conflict result. Other failures propagate.
     *
     * @param entity entity name
     * @param record record to insert
     * @return insertion outcome
     */
    default @NotNull MutationResult insertResult(@NotNull String entity, @NotNull EntityRecord record) {
        try {
            insert(entity, record);
            return MutationResult.changed(1, MutationResult.Outcome.INSERTED);
        } catch (Conflict conflict) {
            return new MutationResult(
                    0,
                    0,
                    1,
                    MutationResult.Outcome.CONFLICT,
                    List.of(new ConflictDetail(ConflictDetail.Kind.UNKNOWN, null, null, conflict.getMessage())));
        }
    }

    /**
     * Applies a mutation and returns its outcome.
     *
     * @param entity entity name
     * @param predicate condition selecting records
     * @param mutation changes to apply
     * @return update outcome
     */
    default @NotNull MutationResult updateResult(
            @NotNull String entity, @NotNull Predicate predicate, @NotNull Mutation mutation) {
        return MutationResult.changed(update(entity, predicate, mutation), MutationResult.Outcome.UPDATED);
    }

    /**
     * Deletes records and returns the outcome.
     *
     * @param entity entity name
     * @param predicate condition selecting records
     * @return deletion outcome
     */
    default @NotNull MutationResult deleteResult(@NotNull String entity, @NotNull Predicate predicate) {
        return MutationResult.changed(delete(entity, predicate), MutationResult.Outcome.DELETED);
    }

    /**
     * Inserts or updates a record matching an identity.
     *
     * @param entity entity name
     * @param identity condition identifying the record to update
     * @param insert values to insert when no record matches
     * @param update mutation applied to a matching record
     * @return insert or update outcome
     * @throws Capability if the adapter does not support atomic upserts
     */
    default @NotNull MutationResult upsert(
            @NotNull String entity,
            @NotNull Predicate identity,
            @NotNull EntityRecord insert,
            @NotNull Mutation update) {
        throw new Capability("Adapter does not support atomic upsert");
    }
}
